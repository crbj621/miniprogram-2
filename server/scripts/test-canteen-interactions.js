'use strict'
// Run in a disposable database only; exercise the real SDK, transactions and independent connections.
const assert = require('node:assert/strict')
const crypto = require('node:crypto')
const cloud = require('campus-server-sdk')
const service = require('../services/canteen_reviews')
const db = cloud.database(), prefix = 'canteen-sql-' + crypto.randomBytes(6).toString('hex')
let checks = 0
const check = (condition, message) => { assert.ok(condition, message); checks++ }
const call = (openid, action, data = {}) => cloud.__runWithContext({ openid }, () => service.main({ action, ...data }))
async function main() {
  assert.match(process.env.DB_NAME || '', /^campus_test_/, 'requires isolated campus_test_ database')
  await cloud.__ensureSchema()
  await db.collection('global_settings').doc('canteen-test').set({ data: { modules: { canteen: { enabled: true } } } })
  for (const openid of ['a', 'b', 'admin', 'v1', 'v2', 'v3', 'v4', 'v5']) await db.collection('users').doc(openid).set({ data: { openid, nickName: openid, avatarUrl: 'https://www.crbuj.icu/campus-api/uploads/avatar.png' } })
  await db.collection('global_admin').doc('canteen-test-admin').set({ data: { loginOpenid: 'admin', status: 'active', role: 'super' } })
  const form = { stallName: prefix + 'Ａ', location: '一食堂 二楼 ３号', dishName: '番茄面', description: '真实SQL临时回归', meals: ['lunch', 'dinner'] }
  const both = await Promise.all([call('a', 'submit', { ...form, clientId: 'a' }), call('b', 'submit', { ...form, stallName: prefix + 'a', location: '一食堂二楼3号', clientId: 'b' })])
  check(both.every(row => row.success), 'concurrent writers both succeed')
  check(both[0].stallId === both[1].stallId && both[0].dishId === both[1].dishId, 'one canonical stall and dish')
  check((await db.collection('canteen_stalls').get()).data.length === 1, 'SQL one stall')
  check((await db.collection('canteen_dishes').get()).data.length === 1, 'SQL one dish')
  const stallId = both[0].stallId, dishId = both[0].dishId
  check((await call('a', 'checkStall', { stallName: prefix + 'a', location: '一食堂二楼3号' })).exists, 'normalized existence check')
  const saved = await Promise.all([call('a', 'saveReview', { dishId, clientId: 'one', score: 5, comment: '第一次' }), call('a', 'saveReview', { dishId, clientId: 'one', score: 5, comment: '第一次' })])
  check(saved.every(row => row.success) && saved[0].id === saved[1].id, 'concurrent comment retry idempotent')
  await call('a', 'saveReview', { dishId, clientId: 'two', score: 2, comment: '最新评分' })
  await call('a', 'saveReview', { dishId, clientId: 'chat', comment: '交流' })
  await call('b', 'saveReview', { dishId, clientId: 'b', score: 4, comment: '另一位' })
  const detail = await call('a', 'reviews', { dishId })
  check(detail.count === 2 && detail.reviewCount === 4 && detail.score === 3 && detail.myRating.score === 2, 'one latest rating per user with multiple comments')
  check(detail.reviews.every(row => row.avatarUrl && !Object.hasOwn(row, 'openid')), 'avatars without private openid')
  const latest = detail.reviews.find(row => row.mine && row.latestRating)
  const votes = await Promise.all(['v1', 'v2', 'v3', 'v4', 'v5'].map(openid => call(openid, 'voteReview', { reviewId: latest._id, vote: 'down' })))
  check(votes.every(row => row.success), 'concurrent feedback transactions')
  check((await call('a', 'reviews', { dishId })).myRating.status === 'contested', 'threshold suspends associated latest score')
  check((await call('a', 'reviews', { dishId })).count === 1, 'suspended vote excluded from arithmetic mean')
  check(!(await call('a', 'resolveDispute', { id: latest._id, resolution: 'restore' })).success, 'moderation authorization')
  await call('a', 'deleteReview', { reviewId: latest._id })
  await call('admin', 'resolveDispute', { id: latest._id, resolution: 'restore' })
  check((await call('a', 'reviews', { dishId })).count === 2, 'restore independent score after comment deletion')
  check((await db.collection('canteen_reviews').doc(latest._id).get()).data.status === 'deleted', 'restore does not restore deleted comment')
  const picture = 'https://www.crbuj.icu/campus-api/uploads/one.jpg', picture2 = 'https://www.crbuj.icu/campus-api/uploads/two.jpg'
  const photo1 = await call('a', 'submit', { kind: 'photo', clientId: 'photo-1', stallId, image: picture })
  const photo2 = await call('b', 'submit', { kind: 'photo', clientId: 'photo-2', stallId, image: picture2 })
  check((await db.collection('canteen_stalls').doc(stallId).get()).data.image === picture, 'first photograph only fills empty cover')
  check((await call('a', 'detail', { stallId })).photos.length === 2, 'public contribution gallery')
  await call('admin', 'setStallCover', { id: photo2.id })
  check((await db.collection('canteen_stalls').doc(stallId).get()).data.image === picture2, 'admin cover selection')
  check(!(await call('a', 'updateSubmission', { id: both[1].id, image: picture, dishName: '番茄面', description: '越权' })).success, 'edit ownership checked server-side')
  check((await call('a', 'updateSubmission', { id: both[0].id, image: picture, dishName: '番茄鸡蛋面', description: '更新说明', price: 9, meals: ['lunch', 'dinner'] })).success, 'owner edits original dish')
  check((await call('a', 'reviews', { dishId })).dish.name === '番茄鸡蛋面', 'editing preserves original comments and id')
  check(!(await call('a', 'deleteSubmission', { id: both[1].id })).success, 'delete ownership')
  const race = await Promise.all([call('b', 'deleteSubmission', { id: photo2.id }), call('admin', 'setStallCover', { id: photo2.id })])
  check(race[0].success, 'cover deletion commits')
  check((await db.collection('canteen_stalls').doc(stallId).get()).data.image === picture, 'concurrent cover selection cannot restore deleted photo')
  await call('a', 'deleteSubmission', { id: both[0].id })
  check((await db.collection('canteen_dishes').doc(dishId).get()).data.status === 'published', 'shared rated dish preserved after author withdrawal')
  const breakfast = await call('a', 'submit', { kind: 'dish', clientId: 'breakfast', stallId, dishName: '豆浆', description: '早餐', meals: ['breakfast'] })
  check(breakfast.success, 'breakfast submission')
  check((await call('a', 'list', { meal: 'lunch' })).dishes.every(row => row._id !== breakfast.dishId), 'lunch excludes breakfast-only dishes')
  check((await call('a', 'random', { meal: 'breakfast', mode: 'all' })).dish._id === breakfast.dishId, 'random respects meal selection')
  check((await call('a', 'list', { meal: 'lunch' })).dishes[0]._id === (await call('a', 'list', { meal: 'dinner' })).dishes[0]._id, 'lunch and dinner share same canonical dish')
  await legacyClients(stallId)
  await db.collection('global_settings').doc('canteen-test').update({ data: { 'modules.canteen.enabled': false } })
  check(!(await call('a', 'updateSubmission', { id: photo1.id, image: picture })).success, 'module gate for added actions')
  console.log('Canteen isolated MariaDB regression: ' + checks + ' checks passed')
}
async function legacyClients(stallId) {
  const dish = await call('admin', 'saveDish', { stallId, name: prefix + '旧版兼容', status: 'published' })
  const firstPayload = { dishId: dish.id, score: 5, comment: '正式旧版', images: ['https://www.crbuj.icu/campus-api/uploads/old.jpg'] }
  const first = await call('a', 'saveReview', firstPayload)
  check(first.success, 'published client without clientId posts')
  check((await call('a', 'saveReview', firstPayload)).id === first.id, 'published retry replays current score comment')
  const next = { ...firstPayload, score: 2, comment: '正式旧版更新' }
  const both = await Promise.all([call('a', 'saveReview', next), call('a', 'saveReview', next)])
  check(both.every(row => row.success) && both[0].id === both[1].id, 'concurrent legacy retries create one comment')
  check((await call('a', 'reviews', { dishId: dish.id })).reviewCount === 2, 'legacy updates append without duplicate retries')
  const repeated = await call('a', 'saveReview', firstPayload)
  check(repeated.success && repeated.id !== first.id, 'legacy A to B to A creates a new latest score')
  check((await call('a', 'reviews', { dishId: dish.id })).myRating.score === 5, 'legacy latest score remains one vote')
  const modern = await call('a', 'saveReview', { ...next, clientId: 'modern-with-legacy', score: 3 })
  check(modern.success, 'new client remains supported alongside old')
  const oldAgain = await call('a', 'saveReview', firstPayload)
  check(oldAgain.success && oldAgain.id !== repeated.id, 'legacy score updates after modern score')
  check(!(await call('a', 'saveReview', { dishId: dish.id, comment: '旧版必须选分' })).success, 'old scored contract still validates score')
  const liked = await call('b', 'likeReview', { reviewId: oldAgain.id })
  check(liked.success && liked.isLiked && liked.likeCount === 1, 'published likeReview response preserved')
  await call('a', 'deleteReview', { reviewId: oldAgain.id })
  const recreated = await call('a', 'saveReview', firstPayload)
  check(recreated.success && recreated.id !== oldAgain.id, 'legacy resend does not restore deleted record')
  await Promise.all(['v1', 'v2', 'v3', 'v4', 'v5'].map(openid => call(openid, 'voteReview', { reviewId: recreated.id, vote: 'down' })))
  const before = (await call('a', 'reviews', { dishId: dish.id })).reviewCount
  check(!(await call('a', 'saveReview', next)).success, 'legacy cannot bypass disputed score')
  check((await call('a', 'reviews', { dishId: dish.id })).reviewCount === before, 'rejected legacy request does not append a comment')
  await call('admin', 'resolveDispute', { id: recreated.id, resolution: 'restore' })
  check((await call('a', 'saveReview', next)).success, 'legacy posting resumes after moderator restores rating')
}
main().finally(() => cloud.__getPool().end()).catch(error => { console.error(error); process.exitCode = 1 })
