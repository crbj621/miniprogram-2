const lastPicked: { [key: string]: number } = {}
function toCopy(pair: CopyPair): PageCopy {
  return { title: pair[0], subtitle: pair[1], greeting: pair[2] || '' }
}

export function getPageCopy(scope: PageCopyScope): PageCopy {
  const choices = copies[scope]
  const last = lastPicked[scope]
  let index = Math.floor(Math.random() * (last === undefined ? choices.length : choices.length - 1))
  if (last !== undefined && index >= last) index += 1
  lastPicked[scope] = index
  return toCopy(choices[index])
}

// 在进入页面时选择一次；onShow、输入、请求回包和重绘不会换文案。
export function withPageCopy<T extends { [key: string]: any }>(scope: PageCopyScope, definition: T): T {
  return {
    ...definition,
    data: { ...definition.data, pageCopy: toCopy(copies[scope][0]) },
    onLoad(this: any, options: any) {
      this.setData({ pageCopy: getPageCopy(scope) })
      return definition.onLoad && definition.onLoad.call(this, options)
    }
  } as T
}
